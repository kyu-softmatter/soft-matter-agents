#!/usr/bin/env python3
"""Render each calculator's SKILL.md from contracts/calculations.json (plan.md 4.5.2.2).

    python contracts/tools/calc_skills.py           # write every skill the table declares
    python contracts/tools/calc_skills.py --check   # exit 1 if any skill differs or is stray

The table is the record and the skills are generated from it (P3). A skill
says when its calculator runs, which inputs it takes, which store entries
hold its formula, and which module computes it. It never says how to compute
the bound, because a number a model works out by following a skill's text is
a model's number and cannot enter a card.

A skill directory named `calc-*` under an agent's `.claude/skills/` that no
calculator declares is stray, and `--check` reports it: a removed calculator
must not leave a skill that still tells a session to run it.

Standard library only, and nothing newer than Python 3.9, so bare `python`
runs it on every computer here.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TABLE = REPO / "contracts" / "calculations.json"
AGENTS = ("microscope_agent", "simulation_agent")
HEADER = ("<!-- Generated by contracts/tools/calc_skills.py from contracts/calculations.json. "
          "Edit the table and run the tool again; an edit made here is overwritten. -->")


def skill_name(calc_id: str) -> str:
    return "calc-" + calc_id.replace("_", "-")


def rows_for(table: dict, calc_id: str, key: str) -> list[tuple[str, list[str], str]]:
    out = []
    for row in table["rows"]:
        for item in row.get(key, []):
            if item["calculator"] == calc_id:
                out.append((row["observable"], row["configurations"], item["why"]))
    return out


def render(table: dict, calc: dict) -> str:
    cid = calc["id"]
    name = skill_name(cid)
    axis = calc["axis"].upper()
    description = (f"Calculator {cid} (axis {axis}, bounds {calc['parameter']}). Use in S3 only when "
                   "contracts/calculations.json requires it for the question's observable and "
                   "configuration. It runs code, never a calculation done by hand.")
    lines = ["---", f"name: {name}", f"description: {json.dumps(description, ensure_ascii=False)}", "---", "",
             HEADER, "", f"# {cid}", "", f"Axis {axis}, bounding `{calc['parameter']}`.", "",
             f"**The bound, in words.** {calc['statement'][:1].upper() + calc['statement'][1:]}.", "",
             "## When it runs", ""]

    required = rows_for(table, cid, "required")
    excused = rows_for(table, cid, "not_required")
    if required:
        lines += ["Only when the question's observable and configuration have a row in "
                  f"`contracts/calculations.json` that lists `{cid}` under `required`. Today:", ""]
        for obs, confs, why in required:
            lines.append(f"- `{obs}` on {', '.join('`' + c + '`' for c in confs)}: {why}")
        lines.append("")
    else:
        lines += ["No row requires it today.", ""]
    if excused:
        lines += ["Rows that leave it out on purpose, with the reason the card writes:", ""]
        for obs, confs, why in excused:
            lines.append(f"- `{obs}` on {', '.join('`' + c + '`' for c in confs)}: {why}")
        lines.append("")
    lines += [
        "When a row covers the question and does not require this bound, the card writes it as "
        "abstained, kind `not_requested`, with the row's reason or, where the row names it in neither "
        "list, the table's `default_not_requested_reason`. It is never silently absent. Where no row "
        "covers the question, the axis runs as it did before the table existed.", "",
        "## Inputs: these, and nothing else", ""]
    if calc["needs"]:
        lines += [f"- `{n}`" for n in calc["needs"]] + [""]
    else:
        lines += ["- none", ""]
    lines += [
        "Ask the librarian for each one with the question's issued `caller_id`, or take it from the goal "
        "where the goal declares it as a design input. Do not ask for anything this list does not name. "
        "An input that does not come back goes into `missing`, and the bound is abstained, kind "
        "`no_input`. Never fill a gap with an estimate of your own: a value a model makes up cannot "
        "enter a card.", "", "## The formula is the store's", ""]
    if calc["formula_entries"]:
        lines += ["The code implements these entries and cites each one in the bound's `basis` as "
                  "`kb:<entry_id>`:", ""]
        lines += [f"- `{e}`" for e in calc["formula_entries"]] + [""]
        lines += ["An entry the store does not hold yet makes the bound abstained, kind `no_input`, with "
                  "the entry named in `missing`, and the librarian is asked to enter it. A formula is "
                  "never copied into code or into a card from memory.", ""]
    else:
        lines += [calc.get("note", "This calculator names no store entry for its formula."), ""]
    lines += ["## Run the code", "", f"`{calc['code']}`, status **{calc['status']}**.", ""]
    if calc["status"] == "built":
        lines += ["The module computes this bound when its axis runs, and the axis card carries the "
                  "outcome. Run the module and read the card. Never redo its arithmetic in conversation.", ""]
    else:
        lines += ["The module does not exist yet. Until it does, the card writes this bound as abstained, "
                  f"kind `no_input`, with `calculator:{cid}` in `missing`. Do not compute the bound by hand "
                  "in the meantime.", ""]
    lines += [
        "## What it never does", "",
        "It does not decide whether a run may start. The checks of the person's approval, the safety "
        "limits, the Micro-Manager configuration and the run lock stay in the runtime's code, which runs "
        "on every run whatever any skill says.", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if any skill differs from the table or is stray")
    args = ap.parse_args(argv)

    table = json.loads(TABLE.read_text(encoding="utf-8"))
    wanted: dict[Path, str] = {}
    problems: list[str] = []
    for calc in table["calculators"]:
        path = REPO / calc["skill"]
        if path.parent.name != skill_name(calc["id"]):
            problems.append(f"{calc['id']}: skill path {calc['skill']} is not .claude/skills/{skill_name(calc['id'])}/SKILL.md")
            continue
        if not calc["skill"].startswith(calc["agent"] + "/"):
            problems.append(f"{calc['id']}: skill {calc['skill']} is outside its agent, {calc['agent']}")
            continue
        wanted[path] = render(table, calc)

    stray = []
    for agent in AGENTS:
        base = REPO / agent / ".claude" / "skills"
        if base.is_dir():
            for d in sorted(base.glob("calc-*")):
                if d / "SKILL.md" not in wanted:
                    stray.append(d.relative_to(REPO).as_posix())

    if args.check:
        differ = [p.relative_to(REPO).as_posix() for p, text in wanted.items()
                  if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != text]
        for line in problems + [f"differs from the table: {d}" for d in differ] + [f"stray: {s}" for s in stray]:
            print(line)
        if problems or differ or stray:
            print(f"calc_skills: {len(differ)} differ, {len(stray)} stray, {len(problems)} bad paths "
                  "-- run python contracts/tools/calc_skills.py")
            return 1
        print(f"calc_skills: {len(wanted)} skills current")
        return 0

    for line in problems:
        print(line)
    for path, text in wanted.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    for s in stray:
        print(f"stray, not removed: {s} -- remove it by hand once you have read it")
    print(f"calc_skills: wrote {len(wanted)} skills")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
